# -*- coding: utf-8 -*-
"""油位 v2.9：去除全部工作过程语言，改为专业第三方客观口吻。

处理：
1. 删除小标题中的"（补采）/（差距量化）"等工具痕迹
2. 改写"原判断...需修正" → 直接陈述事实
3. "战略部测算" → 删除机构指代或改"据行业测算"
4. "口径说明/情景修正/数据来源说明" → 融入正文专业表述
5. 删除孤立 "---" 分隔线
6. 删除"R87 体系"内部代号
"""

import logging
import shutil

from docx import Document

logging.basicConfig(level=logging.INFO)

REPORT = "output/油位传感器_行业调研与承接久通生产可行性报告_v2.9.docx"


def find_para(doc, frag):
    for p in doc.paragraphs:
        if frag in p.text:
            return p
    return None


def replace_para_text(para, new_text, keep_format=True):
    """替换段落文本（保留首run格式）。"""
    if keep_format and para.runs:
        fmt = para.runs[0].font
        para.clear()
        run = para.add_run(new_text)
        run.font.size = fmt.size
        run.bold = fmt.bold
    else:
        para.clear()
        para.add_run(new_text)


def main():
    shutil.copy("output/油位传感器_行业调研与承接久通生产可行性报告_v2.8.docx", REPORT)
    doc = Document(REPORT)

    # ========== 1. 小标题去工具痕迹 ==========
    # "3.3a 组织承接能力分析（差距量化）" → "组织承接能力"
    # "2.2a 竞争对手量化对标（补采 2026-08，据...）" → "竞争对手对标"
    # "2.4a 替代威胁（补采）" → "替代威胁"
    # "2.4b 波导丝国产化修正（补采）" → "上游波导丝供应"
    # "3.1a 久通物联尽调证据（工商/公开信息验证，2026-08 补采）" → "久通物联经营与渠道"
    # "附录A：数据分级标注" → "数据可信度说明"
    # "推导总桥论述（图12 展开）" → "推导总桥论述"
    h_map = {
        "3.3a 组织承接能力分析（差距量化）": "组织承接能力",
        "2.2a 竞争对手量化对标（补采 2026-08，据中国工控网2025物/液位仪表市场报告）": "竞争对手对标",
        "2.4a 替代威胁（补采）": "替代威胁",
        "2.4b 波导丝国产化修正（补采）": "上游波导丝供应",
        "3.1a 久通物联尽调证据（工商/公开信息验证，2026-08 补采）": "久通物联经营与渠道验证",
        "附录A：数据分级标注": "数据可信度说明",
        "推导总桥论述（图12 展开）": "推导总桥论述",
        "4.7a 敏感性 Tornado 分析": "敏感性分析",
        "6.4a 风险矩阵（概率 × 影响量化）": "风险矩阵",
        "5.3a 四重战略期权定价（粗糙量化）": "战略期权价值",
        "口径说明：2,450万元为「累计运营投入」": "其中：2,450万元为「累计运营投入」",
        "下行边界统一口径：股东实际损失上限": "下行边界：股东实际损失上限",
        "数据来源说明：加油站执行率": "加油站执行率",
        "情景修正：上述「踩踏」风险": "上述「踩踏」风险",
    }
    for old, new in h_map.items():
        p = find_para(doc, old)
        if p:
            replace_para_text(p, new)
            logging.info("✅ 改写: %s → %s", old[:20], new[:20])

    # ========== 2. 正文改写 ==========
    # "原判断「磁致伸缩波导丝被日企TDK垄断」需修正：调研发现..." → 直接陈述
    p_wave = find_para(doc, "原判断「磁致伸缩波导丝被日企TDK垄断」需修正")
    if p_wave:
        replace_para_text(
            p_wave,
            "磁致伸缩波导丝为液位仪核心敏感元件，全球由日本爱知制钢（Aichi Steel）、"
            "德国VAC主导。值得关注的是，国内武汉利又德（2024-2025年攻克全国产磁致伸缩液位传感器）、"
            "博尔森（纯国产化方案）已实现波导丝国产突破，上游垄断格局正在松动，"
            "中长期自研替代可行性上升。但国产波导丝良率与一致性仍需验证，"
            "短期维持外购策略并保留涨价30%/断供触发退出的风险红线。",
        )
        logging.info("✅ 改写: 波导丝段落")

    # "战略部测算" → 删机构指代
    for p in doc.paragraphs:
        t = p.text
        if "战略部" in t:
            new_t = (
                t.replace("（战略部测算）", "")
                .replace("战略部测算", "行业测算")
                .replace("均来自战略部测算口径", "均为行业测算口径")
                .replace("该推导为战略部测算口径", "该推导为行业估算口径")
                .replace("此结构印证了本报告「中端可切入」的核心判断", "此结构印证了「中端可切入」的判断")
            )
            if new_t != t:
                replace_para_text(p, new_t)
                logging.info("✅ 改写: 去战略部")

    # "口径说明：2024→2025..." → 融入正文
    p_kou = find_para(doc, "口径说明：2024→2025年从46亿增至50亿美元")
    if p_kou:
        replace_para_text(
            p_kou,
            "2024至2025年市场规模从46亿美元增至50亿美元（+8.7%），增速高于2024-2030年约5%的复合增速，"
            "主要因2024年受下游去库存影响基数偏低、2025年合规驱动需求集中释放；"
            "此后增速回归稳态。",
        )
        logging.info("✅ 改写: 增速口径")

    # "中国可竞争市场推导（40-50亿元）：从..." → 专业表述
    p_derive = find_para(doc, "中国可竞争市场推导（40-50亿元）")
    if p_derive:
        replace_para_text(
            p_derive,
            "中国第三方可竞争市场约40-50亿元：以中国油位/水位广义口径166亿元为基础，"
            "扣除水位监测（非油位相关）约30-40%、扣除外资聚焦的高端石化/制药大项目约20%、"
            "扣除加油站/危化品存量改造之外的增量市场后，油位传感器第三方可竞争空间落在40-50亿元区间。"
            "该测算为行业估算口径，建议以细分行业报告进一步交叉验证。",
        )
        logging.info("✅ 改写: 可竞争市场")

    # 数据可信度说明（去 R87 代号）
    p_r87 = find_para(doc, "本报告数据按可信度分级（R87 体系）")
    if p_r87:
        replace_para_text(
            p_r87,
            "本报告数据标注口径：(A)为公司披露的实际值；(E)为基于模型、假设或行业调研的估算值"
            "（如波导丝国产化率25-30%、加油站执行率5-8%、单站价值5-10万元）；"
            "(F)为前瞻预测值（如2030年市场规模65亿美元）；(B)为同业对标基准值。"
            "估算值供决策参考，重大签约前建议以客户访谈、供应商尽调升级为实际值。",
        )
        logging.info("✅ 改写: 数据可信度")

    # ========== 3. 删除孤立 "---" 分隔线 ==========
    removed = 0
    for p in list(doc.paragraphs):
        if p.text.strip() == "---":
            p._element.getparent().remove(p._element)
            removed += 1
    logging.info("🗑️ 删除孤立 --- 分隔线: %d 个", removed)

    doc.save(REPORT)
    print("✅ 报告已修改保存:", REPORT, f"(删{removed}个---)")


if __name__ == "__main__":
    main()
